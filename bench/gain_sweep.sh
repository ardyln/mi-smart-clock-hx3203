# HX3203 gain sweep under a fixed light: one root session, a few dozen reads, unloads i2c-dev at the end.
D=/data/local/tmp/hx3203
grep -q '^i2c_dev ' /proc/modules || insmod $D/i2c-dev.ko || exit 1
w() { i2cset -f -y 0 0x44 $1 $2 b; }
g() { i2cget -f -y 0 0x44 $1; }
w 0x01 0x70; w 0x02 0x06; w 0x0c 0x22; w 0x16 0x36; w 0x0b 0x00; w 0x01 0x74; w 0x0c 0x22
for gain in 0x00 0x01 0x02 0x03 0x04 0x05 0x06 0x07 0x08 0x10 0x20 0x40 0x80 0xff; do
    w 0x0b $gain
    sleep 2
    for n in 1 2 3; do
        echo "gain=$gain readback=$(g 0x0b) 08=$(g 0x08) 09=$(g 0x09) 0a=$(g 0x0a) 0d=$(g 0x0d) 0e=$(g 0x0e) 0f=$(g 0x0f)"
        sleep 1
    done
done
w 0x0b 0x00
rmmod i2c_dev
